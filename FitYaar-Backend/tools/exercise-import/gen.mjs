// Generates V19__Import_Exercise_Library.sql from the vendored free-exercise-db snapshot.
// Public domain source (The Unlicense). Run: node tools/exercise-import/gen.mjs
import { readFileSync, writeFileSync } from "node:fs";

const BASE = "D:/FitYaar/FitYaar-Backend";
const SRC = `${BASE}/tools/exercise-import/free-exercise-db.json`;
const OUT = `${BASE}/src/main/resources/db/migration/V19__Import_Exercise_Library.sql`;

const fed = JSON.parse(readFileSync(SRC, "utf8"));

// FED muscle vocab → FitYaar MuscleGroup enum (coarse; refined by name heuristics below).
const MUSCLE = {
  abdominals: "ABS", biceps: "BICEPS", calves: "CALVES", chest: "CHEST",
  forearms: "FOREARMS", glutes: "GLUTES", hamstrings: "HAMSTRINGS", lats: "LATS",
  "lower back": "LOWER_BACK", "middle back": "UPPER_BACK", neck: "NECK",
  quadriceps: "QUADRICEPS", traps: "TRAPS", triceps: "TRICEPS",
  shoulders: "FRONT_DELTS", adductors: "QUADRICEPS", abductors: "GLUTES",
};
const EQUIP = {
  barbell: "BARBELL", "e-z curl bar": "BARBELL", dumbbell: "DUMBBELL", cable: "CABLE",
  machine: "MACHINE", kettlebells: "KETTLEBELL", bands: "BAND", "body only": "NO_EQUIPMENT",
};

const unmapped = new Set();
function mapMuscle(m, nameLower) {
  let e = MUSCLE[m];
  if (!e) { unmapped.add(m); return null; }
  if (m === "chest") {
    if (nameLower.includes("incline")) e = "UPPER_CHEST";
    else if (nameLower.includes("decline")) e = "LOWER_CHEST";
  } else if (m === "shoulders") {
    // Order matters: "rear lateral raise" is a rear-delt move, so check rear/reverse first.
    if (nameLower.includes("rear") || nameLower.includes("reverse")) e = "REAR_DELTS";
    else if (nameLower.includes("lateral") || nameLower.includes("side")) e = "SIDE_DELTS";
    else e = "FRONT_DELTS";
  }
  return e;
}
const mapEquip = (e) => EQUIP[e] || "OTHER";
const mapCategory = (x) =>
  x.equipment === "body only" ? "BODYWEIGHT" : x.category === "cardio" ? "CARDIO" : "STRENGTH";
function mapType(x, nameLower) {
  if (x.category === "cardio") return "DISTANCE_DURATION";
  if (x.category === "stretching") return "DURATION";
  if (/(plank|hold|superman|wall sit|dead hang|l-sit|isometric)/.test(nameLower)) return "DURATION";
  if (x.equipment === "body only") return "BODYWEIGHT_REPS";
  return "WEIGHT_REPS";
}
const slugify = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");
const q = (s) => "'" + String(s ?? "").replace(/'/g, "''") + "'";

const seen = new Set();
let collisions = 0, noPrimary = 0;
const cat = {}, typ = {};
const rows = fed.map((x) => {
  const nl = x.name.toLowerCase();
  const prim = [...new Set((x.primaryMuscles || []).map((m) => mapMuscle(m, nl)).filter(Boolean))];
  const sec = [...new Set((x.secondaryMuscles || []).map((m) => mapMuscle(m, nl)).filter(Boolean))]
    .filter((m) => !prim.includes(m));
  if (prim.length === 0) noPrimary++;
  let slug = slugify(x.name), b = slug, n = 2;
  while (seen.has(slug)) { slug = `${b}-${n++}`; collisions++; }
  seen.add(slug);
  const category = mapCategory(x), type = mapType(x, nl);
  cat[category] = (cat[category] || 0) + 1;
  typ[type] = (typ[type] || 0) + 1;
  return {
    name: x.name, slug,
    description: (x.instructions || []).join("\n\n").trim(),
    equipment: mapEquip(x.equipment), type, category, prim, sec,
  };
});

let out = `-- V19: Full exercise catalog reload from free-exercise-db (The Unlicense / public domain).
-- Source: https://github.com/yuhonas/free-exercise-db  (generated by tools/exercise-import/gen.mjs)
-- Pre-prod replace: drops the seeded catalog (is_custom = false) and loads ${rows.length} exercises.
-- Safe: exercise_*_muscle_groups cascade on delete; routine/workout/PR tables are empty at this point.

DELETE FROM exercises WHERE is_custom = false;

`;
for (const r of rows) {
  out += `INSERT INTO exercises (name, slug, description, equipment, exercise_type, category, is_custom, created_at, updated_at)\n`;
  out += `VALUES (${q(r.name)}, ${q(r.slug)}, ${q(r.description)}, ${q(r.equipment)}, ${q(r.type)}, ${q(r.category)}, false, NOW(), NOW());\n`;
  for (const m of r.prim)
    out += `INSERT INTO exercise_primary_muscle_groups (exercise_id, muscle_group) SELECT id, ${q(m)} FROM exercises WHERE slug = ${q(r.slug)};\n`;
  for (const m of r.sec)
    out += `INSERT INTO exercise_secondary_muscle_groups (exercise_id, muscle_group) SELECT id, ${q(m)} FROM exercises WHERE slug = ${q(r.slug)};\n`;
  out += "\n";
}

writeFileSync(OUT, out, "utf8");
console.log("exercises:", rows.length);
console.log("category:", JSON.stringify(cat));
console.log("exercise_type:", JSON.stringify(typ));
console.log("slug collisions resolved:", collisions);
console.log("no-primary-muscle:", noPrimary);
console.log("unmapped FED muscles:", [...unmapped].join(", ") || "(none)");
console.log("wrote", OUT, `(${(out.length / 1024).toFixed(0)} KB)`);
